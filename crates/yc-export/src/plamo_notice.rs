//! The "Built with PLaMo" notice that every distributable artifact must carry.
//!
//! The PLaMo Community License (https://plamo.preferredai.jp/info/plamo-community-license-en)
//! requires, when the model or its outputs are provided to a third party, both a copy of the
//! license (Art. 4(1)(i)) and the statement "Built with PLaMo" in related documentation
//! (Art. 4(1)(ii)). Art. 5(1) additionally requires that published outputs are identified as
//! outputs of the model. Exported resource packs, JARs, shader packs, modpack archives and
//! language files are exactly such redistributions, so each of them gets this notice.

use crate::ExportError;

/// File name of the notice inside an archive or output directory.
pub const PLAMO_NOTICE_FILE_NAME: &str = "PLaMo_NOTICE.txt";

/// Pinned license texts of `pfnet/plamo-3-translate-0.8b-GGUF` at commit
/// `e10c327b7a7ce84ffc427cb4b09360b781429fda`, embedded so the notice never depends on the network.
const PLAMO_LICENSE_JA: &str = include_str!("plamo_license_ja.txt");
const PLAMO_LICENSE_EN: &str = include_str!("plamo_license_en.txt");

const PLAMO_NOTICE_HEADER: &str = "\
Built with PLaMo

このパッケージの翻訳には、YakuCraft で PLaMo 3 Translate（株式会社Preferred Networks）が生成した
テキストが含まれます。PLaMo は PLaMo コミュニティライセンスに基づいて提供されています。
配布する場合は本ファイルを削除せず、同梱したままにしてください。

Translations in this package include text generated by PLaMo 3 Translate (Preferred Networks, Inc.)
using YakuCraft. PLaMo is provided under the PLaMo Community License. Keep this file when you
redistribute the package.

------------------------------------------------------------------------------
PLaMo コミュニティライセンス契約（日本語原文）
------------------------------------------------------------------------------

";

/// Returns the notice file name and its UTF-8 content.
pub fn plamo_notice_file() -> (&'static str, Vec<u8>) {
    let mut content = String::with_capacity(
        PLAMO_NOTICE_HEADER.len() + PLAMO_LICENSE_JA.len() + PLAMO_LICENSE_EN.len() + 128,
    );
    content.push_str(PLAMO_NOTICE_HEADER);
    content.push_str(PLAMO_LICENSE_JA);
    content.push_str(
        "\n------------------------------------------------------------------------------\n\
         PLaMo Community License Agreement (English)\n\
         ------------------------------------------------------------------------------\n\n",
    );
    content.push_str(PLAMO_LICENSE_EN);
    (PLAMO_NOTICE_FILE_NAME, content.into_bytes())
}

/// Writes the notice into `directory`, replacing only a previous notice file.
///
/// Language file exports produce a directory instead of an archive, so the notice cannot be
/// embedded. Only our own file name is overwritten; any other existing file would abort the
/// export elsewhere and must not be replaced here.
///
/// The write goes through the atomic replace helper so a pre-existing symlink named
/// `PLaMo_NOTICE.txt` is replaced as a directory entry instead of being followed, which would
/// otherwise let an export overwrite a file outside the output directory.
pub fn write_plamo_notice_to_directory(
    directory: &std::path::Path,
) -> Result<std::path::PathBuf, ExportError> {
    let (file_name, content) = plamo_notice_file();
    let path = directory.join(file_name);
    crate::atomic_write_file(
        &path,
        true,
        |file| {
            use std::io::Write;
            file.write_all(&content)?;
            Ok(())
        },
        |_| Ok(()),
    )?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn notice_starts_with_the_required_statement_and_embeds_both_license_texts() {
        let (file_name, content) = plamo_notice_file();
        assert_eq!(file_name, "PLaMo_NOTICE.txt");
        let text = String::from_utf8(content).expect("the notice is UTF-8");
        assert_eq!(text.lines().next(), Some("Built with PLaMo"));
        assert!(text.contains("PLaMo 3 Translate"));
        assert!(text.contains("Preferred Networks, Inc."));
        assert!(text.contains("PLaMo コミュニティライセンス契約"));
        assert!(text.contains("PLaMo Community License Agreement"));
        // Article 4 and 5 are the clauses that require the notice and the output attribution.
        assert!(text.contains("第4条（再配布及び表示義務）"));
        assert!(text.contains("Article 4 (Redistribution and Attribution Requirements)"));
        assert!(text.contains("第5条（生成物の利用）"));
        assert!(text.contains("Article 5 (Usage of Outputs)"));
    }
}
